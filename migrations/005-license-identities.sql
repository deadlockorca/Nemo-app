CREATE TABLE IF NOT EXISTS license_identities (
  license_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  device_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  registration_uuid CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_identity_license FOREIGN KEY (license_id) REFERENCES licenses(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
